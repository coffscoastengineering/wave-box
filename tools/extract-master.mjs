// Builds src/master-data.js from the Fusion reference exports. Run: node tools/extract-master.mjs
import fs from 'node:fs';
import { simplify, signedArea, bboxOf } from '../src/geom.js';

const sections = JSON.parse(fs.readFileSync(new URL('../reference/fusion-sections.json', import.meta.url)));

const find = (path) => {
  const s = sections.find((p) => p.path === path);
  if (!s) throw new Error(`missing section ${path}`);
  return s.loops[0].pts;
};
const walnutRaw = find('Sides:1+Side 1:1');
const zShift = -bboxOf([walnutRaw]).z0;

const r3 = (v) => Math.round(v * 1000) / 1000;
const norm = (pts) => {
  let l = simplify(pts.map(([z, y]) => [z + zShift, y]), 0.01).map(([z, y]) => [r3(z), r3(y)]);
  if (signedArea(l) < 0) l = l.reverse();
  return l;
};

const env = (path) => norm(find(path));
const out = {
  design: { H: 299.8, D: 375, W: 300 },
  zShift: r3(zShift),
  walnut: norm(walnutRaw),
  tiers: {
    bottom: { env: env('Bottom:1+Sides (1):1+Component36:1'), y0: 0, y1: 90 },
    middle: { env: env('Middle:1+Sides (2):1+Component26:1'), y0: 100, y1: 190 },
    top: { env: env('Top:1+Body:1+Component41:1'), y0: 200, y1: 299.8,
      wallTop: r3(bboxOf([find('Top:1+Body:1+Component37:1')]).y1) },
  },
  // Measured directly from the real dowel bodies in the "Box Revision" Fusion document
  // (2026-09-30), which models all 5 side-fixing dowels as actual 3D bodies spanning the
  // stand-off gap — supersedes the 3-circle sketch in fusion-master.json and this file's
  // earlier 2 computed middle-tier positions. Fusion coordinates (x=width, y=height,
  // z=depth before zShift) read via MCP from "Side:1+Dowels (2):2", bodies at x≈-156 (the
  // stand-off gap, not the carcass end or the walnut body itself): (-114,25), (73.87,
  // 142.84), (160,265), (-48.07,142.84), (111,25); z here = raw z + zShift. All 5 clear the
  // 5 mm edge-margin warning by 13.8–23.4 mm at design size. (The separate "Dowels" bodies
  // under Middle/Bottom, at x≈±94–114 inside the drawer footprint, are unrelated drawer
  // joinery, not side-fixing dowels — not used here.)
  dowels: [
    { z: r3(-114 + zShift), y: 25, d: 20 },
    { z: r3(73.87 + zShift), y: 142.84, d: 20 },
    { z: r3(160 + zShift), y: 265, d: 20 },
    { z: r3(-48.07 + zShift), y: 142.84, d: 20 },
    { z: r3(111 + zShift), y: 25, d: 20 },
  ],
  // Dowels pinning one tier's board to the next across the 10 mm inter-tier gap, measured
  // the same way from "Bottom:1+Dowels:1" (y≈95, the bottom/middle seam) and
  // "Middle:1+Dowels(1):1" (y≈195, the middle/top seam). x is the board's own width axis
  // (not scaled by depth/height — scaled proportionally to the board's own length instead,
  // in parts.js), symmetric about the board centre; xDesign/halfLenDesign gives that ratio
  // (halfLenDesign = design carcass length / 2 = (300 − 2×6) / 2 = 144).
  interTierSeams: [
    { y: 95, xDesign: 104, halfLenDesign: 144, zs: [r3(58.54 + zShift), r3(-71.44 + zShift)], d: 20 },
    { y: 195, xDesign: 109, halfLenDesign: 144, zs: [r3(99.28 + zShift), r3(-14.58 + zShift)], d: 20 },
  ],
};

fs.writeFileSync(new URL('../src/master-data.js', import.meta.url),
  `// Generated by tools/extract-master.mjs from reference/*.json — do not edit.\nexport const MASTER = ${JSON.stringify(out)};\n`);
console.log('walnut pts', out.walnut.length, 'envs', Object.values(out.tiers).map((t) => t.env.length), 'dowels', out.dowels);
